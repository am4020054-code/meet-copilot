import assert from 'node:assert/strict';
import {harness, success} from './ui_harness.mjs';
const h=await harness({journalEnabled:true});
assert.equal(h.el('error').textContent,'');
h.question('What options are available?');
await h.app.ask(false);
assert.equal(h.requests.length,1);
assert.equal(h.el('answerEn').textContent,success.answer_en);
h.responses.push({ok:true,status:200,data:{...success,answer_en:'A second fictional option is available.'}});
h.question('What is the next option?');
await h.app.ask(false);
assert.equal(h.el('answerEn').textContent,success.answer_en,'new result must not replace the reading position');
h.el('nextAnswer').onclick();
assert.equal(h.el('answerEn').textContent,'A second fictional option is available.');
const started=h.el('start').onclick();
await h.tick(0);
h.sockets[0].receive({type:'Begin'});
await h.tick(0);
h.sockets[1].receive({type:'Begin'});
await started;
assert.equal(h.capture.tab,1);
assert.equal(h.capture.mic,1);
assert.equal(h.sockets.length,2);
h.app.stopAudio();
assert.ok(h.capture.micStops>0);
console.log('UI tests passed: startup, answer generation, history reading lock, tab and mic capture paths');
